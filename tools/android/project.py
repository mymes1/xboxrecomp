"""Generate the per-game native project from the pipeline's analysis.

    <work>/project/xbr_game.json            per-game configuration (editable)
    <work>/project/native/CMakeLists.txt    templates/xbr-game/native
    <work>/project/native/gen/              generated C (the recompile stage)
    <work>/project/native/game/xbr_game_config.c   the configuration, compiled in
    <work>/project/native/game/*.c          hand-written overrides, if any

The configuration starts from the XBE (title, title ID, entry point) and the
defaults below; a profile in tools/android/games/<title_id>.json (or a file
given with --game-config) is merged over it, and an edited xbr_game.json in the
work directory is kept across runs: values the user changed there win.

Runtime settings live in "env": RECOMP_* variables the title needs (see
docs/runtime/environment-variables.md). They are compiled in as title
defaults; the environment, and the Android launcher's options, still win.
"""

import json
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TEMPLATE = os.path.join(ROOT, "templates", "xbr-game", "native", "CMakeLists.txt")
PROFILES = os.path.join(ROOT, "tools", "android", "games")

DEFAULTS = {
    "schema": 1,
    "title": None,
    "title_id": None,
    "entry_point": None,
    "app_name": None,
    "package": None,
    "version_code": 1,
    "version_name": "1.0",
    # Retail RAM. 128 (devkit) keeps every section resident, for titles that
    # page sections in with XeLoadSection, which the runtime does not model.
    "total_ram_mb": 64,
    # XINIT_MOUNT_UTILITY_DRIVE needs a raw-disk image POSIX hosts do not have.
    "keep_mount_utility_drive": False,
    "env": {},
    "android": {"min_sdk": 26, "target_sdk": 35, "abi": "arm64-v8a",
                "orientation": "landscape"},
}


class ProjectError(Exception):
    pass


def _merge(base, over):
    out = dict(base)
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = v
    return out


def _c_string(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c in "\\\"":
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def package_name(title_id):
    return "org.xboxrecomp.t%s" % (title_id or "00000000").lower()


def load_config(work, xbe_report, profile_path=None):
    """The merged configuration: defaults < XBE < profile < saved edits."""
    cfg = _merge(DEFAULTS, {})
    title = xbe_report.get("title") or "Xbox title"
    tid = (xbe_report.get("title_id") or "00000000").upper()
    cfg.update(title=title, title_id=tid, entry_point=xbe_report.get("entry_point"),
               app_name=title, package=package_name(tid))
    prof = profile_path or os.path.join(PROFILES, "%s.json" % tid)
    if os.path.exists(prof):
        with open(prof, encoding="utf-8") as f:
            cfg = _merge(cfg, json.load(f))
        cfg["profile"] = os.path.relpath(prof, ROOT) if prof.startswith(ROOT) else prof
    saved = os.path.join(work, "project", "xbr_game.json")
    if os.path.exists(saved):
        with open(saved, encoding="utf-8") as f:
            prev = json.load(f)
        # Keep what the user edited; the XBE-derived identity always follows the disc.
        for k in ("title", "title_id", "entry_point"):
            prev.pop(k, None)
        cfg = _merge(cfg, prev)
    validate(cfg)
    return cfg


def validate(cfg):
    if not re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", cfg["package"] or ""):
        raise ProjectError("package %r is not a valid Android application id" % cfg["package"])
    if cfg["total_ram_mb"] not in (64, 128):
        raise ProjectError("total_ram_mb must be 64 (retail) or 128 (devkit), not %r"
                           % cfg["total_ram_mb"])
    for k, v in cfg["env"].items():
        if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", k) or not isinstance(v, str):
            raise ProjectError("env entry %r=%r: names are upper-case identifiers, values strings"
                               % (k, v))
    a = cfg["android"]
    if a["min_sdk"] < 26 or a["target_sdk"] < a["min_sdk"]:
        raise ProjectError("android.min_sdk must be >= 26 and <= target_sdk")
    if a["abi"] != "arm64-v8a":
        raise ProjectError("only arm64-v8a is supported (got %r)" % a["abi"])


def config_c(cfg):
    entry = int(cfg["entry_point"], 16) if cfg.get("entry_point") else 0
    lines = [
        "/* Generated by tools/android/project.py from <work>/project/xbr_game.json.",
        " * Edit that file and re-run the project stage; changes here are overwritten. */",
        '#include "xbr_host.h"',
        "",
        "static const char *const s_env[] = {",
    ]
    for k in sorted(cfg["env"]):
        lines.append("    %s," % _c_string("%s=%s" % (k, cfg["env"][k])))
    lines += [
        "    0",
        "};",
        "",
        "const XbrGameConfig xbr_game_config = {",
        "    %s," % _c_string(cfg["title"]),
        "    0x%08Xu," % int(cfg["title_id"], 16),
        "    0x%08Xu," % entry,
        "    %du," % cfg["total_ram_mb"],
        "    %d," % (1 if cfg["keep_mount_utility_drive"] else 0),
        "    s_env,",
        "};",
        "",
    ]
    return "\n".join(lines)


def generate(work, xbe_report, profile_path=None, log=print):
    native = os.path.join(work, "project", "native")
    gen = os.path.join(native, "gen")
    if not os.path.isdir(gen) or not any(n.endswith(".c") for n in os.listdir(gen)):
        raise ProjectError("no generated C in %s (run the recompile stage)" % gen)
    cfg = load_config(work, xbe_report, profile_path)
    with open(os.path.join(work, "project", "xbr_game.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=2)
        f.write("\n")
    shutil.copyfile(TEMPLATE, os.path.join(native, "CMakeLists.txt"))
    game = os.path.join(native, "game")
    os.makedirs(game, exist_ok=True)
    with open(os.path.join(game, "xbr_game_config.c"), "w", encoding="utf-8") as f:
        f.write(config_c(cfg))
    overrides = sorted(n for n in os.listdir(game) if n.endswith(".c") and n != "xbr_game_config.c")
    log("project: %s (%s), package %s, %d MB RAM, %d title env defaults%s" % (
        cfg["title"], cfg["title_id"], cfg["package"], cfg["total_ram_mb"], len(cfg["env"]),
        (", overrides: " + ", ".join(overrides)) if overrides else ""))
    return cfg
