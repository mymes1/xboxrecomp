def _data_offset(zf, info):
    with open(zf.filename, "rb") as f:
        f.seek(info.header_offset)
        hdr = f.read(30)
        if hdr[:4] != b"PK\x03\x04":
            return None
        n, m = struct.unpack("<HH", hdr[26:30])
        return info.header_offset + 30 + n + m


def _aapt2_badging(apk):
    aapt2 = build_tool("aapt2")
    if not aapt2:
        return None, "aapt2 not available here"
    r = subprocess.run([aapt2, "dump", "badging", apk], stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True)
    if r.returncode:
        return None, r.stdout[-2000:]
    out = {}
    m = re.search(r"package: name='([^']+)' versionCode='([^']*)' versionName='([^']*)'", r.stdout)
    if m:
        out.update(package=m.group(1), version_code=m.group(2), version_name=m.group(3))
    m = re.search(r"(?:minSdkVersion|sdkVersion):'(\d+)'", r.stdout)
    if m:
        out["min_sdk"] = int(m.group(1))
    m = re.search(r"targetSdkVersion:'(\d+)'", r.stdout)
    if m:
        out["target_sdk"] = int(m.group(1))
    m = re.search(r"launchable-activity: name='([^']+)'", r.stdout)
    if m:
        out["launchable_activity"] = m.group(1)
    m = re.search(r"native-code: (.*)", r.stdout)
    if m:
        out["native_code"] = re.findall(r"'([^']+)'", m.group(1))
    m = re.search(r"application-label:'([^']*)'", r.stdout)
    if m:
        out["label"] = m.group(1)
    return out, None


def _apksigner(apk):
    tool = build_tool("apksigner")
    if not tool:
        return None, "apksigner not available here"
    r = subprocess.run([tool, "verify", "--verbose", "--print-certs", apk],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    schemes = {m.group(1): m.group(2) == "true"
               for m in re.finditer(r"Verified using (v[\d.]+) scheme[^:]*: (true|false)", r.stdout)}
    cert = re.search(r"certificate SHA-256 digest: ([0-9a-f]+)", r.stdout)
    return {"verified": r.returncode == 0, "schemes": schemes,
            "cert_sha256": cert.group(1) if cert else None}, (None if r.returncode == 0 else r.stdout[-2000:])


def check_game_files(sizes, listed, man):
    """The APK's game files against the intake manifest. sizes: {entry name:
    size} of the APK; listed: its assets/xbr/game_files.json. Bundled: every
    file in assets/game with its size. External: none there. Both: every file
    listed with its size and SHA-256 (what an import on the device checks)."""
    bundled = listed.get("bundled", True)
    problems, missing, wrong_size, unlisted = [], [], [], []
    by_path = {f.get("path"): f for f in listed.get("files", [])}
    for e in man["files"]:
        entry = by_path.get(e["path"])
        if not entry or entry.get("size") != e["size"] or entry.get("sha256") != e.get("sha256"):
            unlisted.append(e["path"])
        if bundled:
            size = sizes.get("assets/game/" + e["path"])
            if size is None:
                missing.append(e["path"])
            elif size != e["size"]:
                wrong_size.append(e["path"])
    if missing:
        problems.append("%d game files missing from the APK (first: %s)" % (len(missing), missing[0]))
    if wrong_size:
        problems.append("%d game files have the wrong size (first: %s)" % (len(wrong_size), wrong_size[0]))
    if unlisted:
        problems.append("%d game files not listed with their size and SHA-256 in"
                        " assets/xbr/game_files.json (first: %s)" % (len(unlisted), unlisted[0]))
    packed = sum(1 for n in sizes if n.startswith("assets/game/"))
    if not bundled and packed:
        problems.append("the game files are meant to be imported on the device, but the APK"
                        " holds %d of them" % packed)
    return {"mode": "bundle" if bundled else "external", "expected": len(man["files"]),
            "missing": len(missing), "wrong_size": len(wrong_size), "unlisted": len(unlisted),
            "in_apk": packed, "problems": problems}


def verify(work, apk=None, log=print):
    with open(os.path.join(work, "project", "xbr_game.json"), encoding="utf-8") as f:
        cfg = json.load(f)
    if not apk:
        apk = os.path.join(work, "out", "%s-%s.apk" % (cfg["package"], cfg["version_name"]))
    if not os.path.exists(apk):
        raise ApkError("no APK at %s (run the apk stage)" % apk)
    problems, notes = [], []
    zf = zipfile.ZipFile(apk)
    infos = zf.infolist()
    names = {i.filename: i for i in infos}
    abis = sorted({n.split("/")[1] for n in names if n.startswith("lib/") and n.count("/") >= 2})
    if abis != ["arm64-v8a"]:
        problems.append("native code for %s; expected arm64-v8a only" % (abis or "no ABI"))
    libs = []
    tmp = tempfile.mkdtemp(prefix="xbrapk")
    try:
        for n in LIBS:
            info = names.get("lib/arm64-v8a/" + n)
            if not info:
                problems.append("lib/arm64-v8a/%s missing" % n)
                continue
            off = _data_offset(zf, info)
            stored = info.compress_type == zipfile.ZIP_STORED
            aligned = off is not None and off % PAGE == 0
            if not stored:
                problems.append("%s is compressed (cannot load in place)" % n)
            if not aligned:
                problems.append("%s data at offset %s is not %d-aligned" % (n, off, PAGE))
            p = zf.extract(info, tmp)
            s = elfinfo.Elf(p).summary(native.REQUIRED_SYMBOLS if n == "libmain.so" else ["JNI_OnLoad"])
            missing = [k for k, v in s["symbols_present"].items() if not v]
            if s["machine"] != "aarch64" or s["class"] != "ELF64":
                problems.append("%s is %s %s" % (n, s["class"], s["machine"]))
            if missing:
                problems.append("%s lacks %s" % (n, ", ".join(missing)))
            libs.append({"name": n, "size": info.file_size, "stored": stored, "data_offset": off,
                         "page_aligned": aligned, "machine": s["machine"], "tls": s["tls"],
                         "android_api": s["android_api"], "load_alignment": s["load_alignment"],
                         "guest_functions": s["guest_functions"], "missing_symbols": missing})
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    dex = [n for n in names if re.fullmatch(r"classes\d*\.dex", n)]
    classes = {}
    blob = b"".join(zf.read(n) for n in dex)
    for c in ("Lorg/xboxrecomp/app/LauncherActivity;", "Lorg/xboxrecomp/app/XbrGameActivity;",
              "Lorg/xboxrecomp/app/GameFiles;", "Lorg/xboxrecomp/app/GameZipProvider;",
              "Lorg/libsdl/app/SDLActivity;"):
        classes[c] = c.encode() in blob
        if not classes[c]:
            problems.append("dex lacks %s" % c)
    with open(os.path.join(work, "game_manifest.json"), encoding="utf-8") as f:
        man = json.load(f)
    try:
        listed = json.loads(zf.read("assets/xbr/game_files.json"))
    except (KeyError, ValueError):
        listed = {}
    gf = check_game_files({n: i.file_size for n, i in names.items()}, listed, man)
    problems += gf.pop("problems")
    bundled = gf["mode"] == "bundle"
    for n in ("assets/xbr/game_files.json", "AndroidManifest.xml", "resources.arsc"):
        if n not in names:
            problems.append("%s missing" % n)
    badging, err = _aapt2_badging(apk)
    if badging:
        if badging.get("package") != cfg["package"]:
            problems.append("package %r, expected %r" % (badging.get("package"), cfg["package"]))
        if badging.get("min_sdk") != cfg["android"]["min_sdk"]:
            problems.append("minSdk %s, expected %s" % (badging.get("min_sdk"), cfg["android"]["min_sdk"]))
        if badging.get("target_sdk") != cfg["android"]["target_sdk"]:
            problems.append("targetSdk %s, expected %s" % (badging.get("target_sdk"), cfg["android"]["target_sdk"]))
        if badging.get("launchable_activity") != "org.xboxrecomp.app.LauncherActivity":
            problems.append("launchable activity %r" % badging.get("launchable_activity"))
    else:
        notes.append("manifest not dumped: %s" % err)
    sig, err = _apksigner(apk)
    if sig is not None and not sig["verified"]:
        problems.append("signature does not verify: %s" % err)
    elif sig is None:
        notes.append("signature not checked: %s" % err)
    rep = {"ok": not problems, "apk": os.path.relpath(apk, work), "size": os.path.getsize(apk),
           "sha256": _sha256(apk), "abis": abis, "libraries": libs, "dex": dex,
           "classes": classes, "game_files": gf,
           "manifest": badging, "signature": sig, "problems": problems, "notes": notes}
    _write_json(os.path.join(work, "reports", "apk_verify.json"), rep)
    log("APK verify: %s; %s" % ("ok" if rep["ok"] else "FAILED", "; ".join(problems) or
                               "abis %s, libs stored+aligned, %d game files %s" % (
                                   abis, len(man["files"]),
                                   "bundled" if bundled else "listed for import on the device")))
    if problems:
        raise ApkError("APK verification failed: " + "; ".join(problems))
    return rep


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "verify"])
    ap.add_argument("--work", required=True)
    ap.add_argument("--apk")
    ap.add_argument("--game-files", choices=GAME_FILES_MODES, default="auto",
                    help="build: bundle the game files in the APK, or leave them for the"
                         " launcher to import on the device (auto: bundle what fits)")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "build":
            build(os.path.abspath(a.work), game_files=a.game_files)
        else:
            verify(os.path.abspath(a.work), a.apk)
    except (ApkError, native.NativeError) as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
